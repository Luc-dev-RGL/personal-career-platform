function Decode-Patch {
    param([string]$B64, [string]$Out, [string]$Expected)
    $bytes = [Convert]::FromBase64String(($B64 -replace "\s", ""))
    $sha = [System.Security.Cryptography.SHA256]::Create()
    $hash = ([BitConverter]::ToString($sha.ComputeHash($bytes)) -replace "-", "").ToLower()
    if ($hash -ne $Expected) {
        Write-Host ""
        Write-Host "ERREUR : $Out est corrompu (copie incomplete)." -ForegroundColor Red
        Write-Host "Recopie le bloc correspondant en entier, puis relance le script."
        exit 1
    }
    [System.IO.File]::WriteAllBytes((Join-Path (Get-Location).Path $Out), $bytes)
    Write-Host ("OK        {0}  ({1} octets, integrite verifiee)" -f $Out, $bytes.Length) -ForegroundColor Green
}

function Apply-Patch {
    param([string]$Patch, [string]$Label)
    cmd /c "git apply --check $Patch 2>nul"
    if ($LASTEXITCODE -eq 0) {
        cmd /c "git apply $Patch"
        Write-Host ("APPLIQUE        : {0}" -f $Label) -ForegroundColor Green
        return
    }
    cmd /c "git apply --reverse --check $Patch 2>nul"
    if ($LASTEXITCODE -eq 0) {
        Write-Host ("DEJA APPLIQUE   : {0}  (ignore)" -f $Label) -ForegroundColor Yellow
        return
    }
    cmd /c "git apply --ignore-whitespace --check $Patch 2>nul"
    if ($LASTEXITCODE -eq 0) {
        cmd /c "git apply --ignore-whitespace $Patch"
        Write-Host ("APPLIQUE (CRLF) : {0}" -f $Label) -ForegroundColor Green
        return
    }
